#!/usr/bin/env python3
"""Write the network pin of a browser wallet bundle from a public wallet profile.

A browser wallet bundle is built for exactly one network. This command takes
the network identity of a reviewed public wallet profile
(native-wallet-profile-v1: the 32-byte network identifier and the genesis hash)
and writes it into the bundle as the module `network-pin.js`. The wallet worker
loads that module as part of its own code and refuses a site whose served
configuration, transport description or reported genesis hash differs.

The pin is public. It holds no key, address, endpoint or wallet data. It is a
build input: a devnet bundle is pinned with the devnet profile, a local
rehearsal with the profile of its own local network. Nothing here reads a
network; the genesis hash is whatever the supplied profile states.
"""
import argparse
import hashlib
import json
import os
from pathlib import Path
import re
import tempfile

PIN_FORMAT = "zolana-browser-network-pin-v1"
PIN_URL = "/network-pin.js"
PIN_NAME = "network-pin.js"
ENVIRONMENTS = ("testnet", "mainnet")
MANIFEST_FORMAT = "zolana-browser-assets-v1"
B58 = re.compile(r"[1-9A-HJ-NP-Za-km-z]{32,44}")
HEADER = ("// Network pin of this browser wallet bundle: the one network this build accepts.\n"
          "// Generated by tools/browser_wallet_pin.py from a public wallet profile. Do not edit.\n")
MODULE = re.compile(re.escape(HEADER) + r"export default Object\.freeze\((\{[ -~]{1,512}\})\);\n")


def unique(pairs):
    value = {}
    for key, item in pairs:
        if key in value:
            raise ValueError("Ambiguous JSON object.")
        value[key] = item
    return value


def decode(raw):
    def invalid(_):
        raise ValueError("Nonfinite JSON value.")
    return json.loads(raw, object_pairs_hook=unique, parse_constant=invalid)


def identity(value):
    """Return a validated copy of {"network": [32 bytes], "genesis_hash": base58}."""
    if (not isinstance(value, dict) or set(value) != {"network", "genesis_hash"} or
            not isinstance(value["network"], list) or len(value["network"]) != 32 or
            any(type(n) is not int or not 0 <= n <= 255 for n in value["network"]) or
            not any(value["network"]) or not isinstance(value["genesis_hash"], str) or
            B58.fullmatch(value["genesis_hash"]) is None):
        raise ValueError("Invalid public network identity.")
    return {"network": list(value["network"]), "genesis_hash": value["genesis_hash"]}


def render(network, environment):
    """The exact bytes of network-pin.js for this network and environment."""
    if environment not in ENVIRONMENTS:
        raise ValueError("Environment must be testnet or mainnet.")
    pin = {"format": PIN_FORMAT, "environment": environment, "network": identity(network)}
    body = json.dumps(pin, sort_keys=True, separators=(",", ":"))
    return (HEADER + f"export default Object.freeze({body});\n").encode("ascii")


def parse(raw):
    """Read a pin module strictly. Only the exact rendering of a valid pin is accepted."""
    try:
        text = raw.decode("ascii")
    except UnicodeDecodeError as error:
        raise ValueError("Network pin module is not the generated form.") from error
    match = MODULE.fullmatch(text)
    if match is None:
        raise ValueError("Network pin module is not the generated form.")
    pin = decode(match.group(1))
    if (not isinstance(pin, dict) or set(pin) != {"format", "environment", "network"} or
            pin["format"] != PIN_FORMAT or pin["environment"] not in ENVIRONMENTS):
        raise ValueError("Network pin module is not the generated form.")
    result = {"environment": pin["environment"], "network": identity(pin["network"])}
    if render(result["network"], result["environment"]) != raw:
        raise ValueError("Network pin module is not the generated form.")
    return result


def profile_network(profile):
    """The network identity stated by a public wallet profile."""
    if not isinstance(profile, dict) or profile.get("format") != "native-wallet-profile-v1":
        raise ValueError("A native-wallet-profile-v1 public profile is required.")
    return identity({"network": profile.get("network"), "genesis_hash": profile.get("genesis_hash")})


def replace_file(path, raw):
    handle, pending = tempfile.mkstemp(dir=path.parent, prefix=path.name + ".", suffix=".new")
    try:
        with os.fdopen(handle, "wb") as output:
            output.write(raw)
            output.flush()
            os.fsync(output.fileno())
        os.chmod(pending, 0o644)
        os.replace(pending, path)
    except BaseException:
        Path(pending).unlink(missing_ok=True)
        raise


def stamp(root, pin, manifest_path=None):
    """Write the pin into a bundle root and, if given, list it in the asset manifest.

    Returns the SHA-256 of the pin module and of the manifest as written. The
    manifest digest changes whenever the pin does: it is the value a gateway is
    started with, so a bundle and its pin are reviewed and served as one unit.
    """
    root = Path(root).resolve()
    if not root.is_dir():
        raise ValueError("The bundle root must be an existing directory.")
    target = root / PIN_NAME
    if target.is_symlink() or (target.exists() and not target.is_file()):
        raise ValueError("The pin path in the bundle root is not a regular file.")
    document = None
    if manifest_path is not None:
        manifest_path = Path(manifest_path)
        document = decode(manifest_path.read_bytes())
        if (not isinstance(document, dict) or set(document) != {"format", "assets"} or
                document["format"] != MANIFEST_FORMAT or not isinstance(document["assets"], dict)):
            raise ValueError("A zolana-browser-assets-v1 manifest is required.")
    replace_file(target, pin)
    result = {"pin_sha256": hashlib.sha256(pin).hexdigest(), "assets_sha256": None}
    if document is not None:
        document["assets"][PIN_URL] = {"path": PIN_NAME, "sha256": result["pin_sha256"]}
        raw = (json.dumps(document, sort_keys=True, indent=2) + "\n").encode()
        replace_file(manifest_path, raw)
        result["assets_sha256"] = hashlib.sha256(raw).hexdigest()
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--profile", type=Path, required=True, help="Public wallet profile of the network to pin")
    parser.add_argument("--profile-sha256", required=True, help="Expected SHA-256 of that profile file")
    parser.add_argument("--environment", choices=ENVIRONMENTS, required=True)
    parser.add_argument("--assets-root", type=Path, required=True, help="Bundle directory that receives network-pin.js")
    parser.add_argument("--assets-manifest", type=Path,
                        help="Asset manifest to update with the pin; its new SHA-256 is printed")
    args = parser.parse_args()
    raw = args.profile.read_bytes()
    if len(raw) > 8192 or hashlib.sha256(raw).hexdigest() != args.profile_sha256:
        raise SystemExit("The profile differs from the reviewed digest.")
    try:
        network = profile_network(decode(raw))
        result = stamp(args.assets_root, render(network, args.environment), args.assets_manifest)
    except ValueError as error:
        raise SystemExit(str(error)) from error
    print(json.dumps({"format": "zolana-browser-network-pin-stamp-v1", "environment": args.environment,
                      "genesis_hash": network["genesis_hash"], **result}, sort_keys=True))


if __name__ == "__main__":
    main()
